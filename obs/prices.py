"""List prices (obs/prices.yaml, USD per 1M tokens) and list_cost_usd per llm_request.

list_cost_usd = input x input rate + cache_write x cache_write_input rate (plain input rate when null) + cache_read x cached_input rate + output x output rate, / 1e6.
Cache writes use the 5-minute write rate (cache_write_input) where the table lists one. NULL when the model is not in the table, or a rate needed for a non-zero token count is null.
The YAML is a small fixed subset (scalars, one mapping, a list of flow mappings), parsed here without PyYAML.
"""
import datetime, json, os, re, urllib.request

OR_URL = "https://openrouter.ai/api/v1/models"
OR_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "prices-openrouter.yaml")
GUESS = (("deepseek", "deepseek"), ("kimi", "moonshotai"), ("glm", "z-ai"), ("qwen", "qwen"))

PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "prices.yaml")


def _scalar(v):
    v = v.strip()
    if not v or v in ("null", "~"):
        return None
    if v[0] in "\"'" and v[-1] == v[0]:
        return v[1:-1]
    try:
        return float(v) if re.fullmatch(r"-?\d+(\.\d+)?([eE]-?\d+)?", v) else v
    except ValueError:
        return v


def _flow(s):
    """{k: v, k2: "v, with comma"} -> dict"""
    s = s.strip()[1:-1]
    out, buf, q = [], "", None
    for ch in s:
        if q:
            buf += ch
            if ch == q:
                q = None
        elif ch in "\"'":
            q = ch
            buf += ch
        elif ch == ",":
            out.append(buf)
            buf = ""
        else:
            buf += ch
    if buf.strip():
        out.append(buf)
    d = {}
    for part in out:
        k, _, v = part.partition(":")
        d[k.strip()] = _scalar(v)
    return d


def load(path=PATH):
    doc, key = {}, None
    for raw in open(path, encoding="utf-8"):
        line = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        if not line.startswith(" "):
            k, _, v = line.partition(":")
            key = k.strip()
            doc[key] = _scalar(v) if v.strip() else None
        elif line.strip().startswith("- {"):
            if not isinstance(doc.get(key), list):
                doc[key] = []
            doc[key].append(_flow(line.strip()[2:]))
        else:
            k, _, v = line.strip().partition(":")
            if not isinstance(doc.get(key), dict):
                doc[key] = {}
            doc[key][k.strip()] = _scalar(v)
    return doc


def _per_m(v):
    try:
        return round(float(v) * 1e6, 4)
    except (TypeError, ValueError):
        return None


def fetch_openrouter(out=OR_PATH, url=OR_URL):
    """GET the public OpenRouter model list and write a prices YAML (USD per 1M tokens). Returns the row count."""
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "obs-prices"}), timeout=20) as r:
        data = json.load(r)["data"]
    rows = []
    for m in sorted(data, key=lambda m: m["id"]):
        pr = m.get("pricing") or {}
        row = {"id": m["id"], "provider": m["id"].split("/", 1)[0], "input": _per_m(pr.get("prompt")),
               "cached_input": _per_m(pr.get("input_cache_read")), "output": _per_m(pr.get("completion"))}
        if pr.get("input_cache_write") is not None:
            row["cache_write_input"] = _per_m(pr.get("input_cache_write"))
        row["context_length"] = m.get("context_length")
        rows.append(row)
    def y(v):
        return "null" if v is None else json.dumps(v) if isinstance(v, str) else repr(v)
    with open(out, "w", encoding="utf-8") as f:
        f.write(f"# OpenRouter list prices, USD per 1M tokens. Generated by `obs prices fetch-openrouter`.\n")
        f.write(f'prices_as_of: "{datetime.datetime.now(datetime.timezone.utc).date().isoformat()}"\n')
        f.write(f"source: {url}\nmodels:\n")
        for r in rows:
            f.write("  - {" + ", ".join(f"{k}: {y(v)}" for k, v in r.items()) + "}\n")
    return len(rows)


def norm(s):
    """lowercase; drop dots/dashes/underscores/colon tags and date/version suffixes: 'Kimi-K2.7-code' -> 'kimik27code'"""
    s = (s or "").lower().split(":")[0]
    s = re.sub(r"[-_]?(20\d{2}-?\d{2}-?\d{2}|\d{8}|latest|preview|v\d+)$", "", s)
    return re.sub(r"[^a-z0-9]", "", s)


def provider_guess(model):
    m = (model or "").lower().rsplit("/", 1)[-1]
    for prefix, prov in GUESS:
        if m.startswith(prefix):
            return prov
    return None


class Prices:
    def __init__(self, path=PATH, or_path=OR_PATH):
        doc = load(path)
        self.as_of = doc.get("prices_as_of")
        self.models = {str(m["id"]).lower(): m for m in doc.get("models") or [] if m.get("id")}
        odoc = load(or_path) if or_path and os.path.exists(or_path) else {}
        self.or_as_of = odoc.get("prices_as_of")
        self.or_models = {str(m["id"]).lower(): m for m in odoc.get("models") or [] if m.get("id")}
        self._cache = {}
        self._src = {}

    def asof_text(self):
        t = f"list prices as of {self.as_of}"
        return t + (f"; OpenRouter prices as of {self.or_as_of}" if self.or_as_of else "")

    def _openrouter(self, m):
        """-> (row, rule) by exact id, provider-guess/<model>, then normalised match within the provider."""
        if m in self.or_models:
            return self.or_models[m], "openrouter-exact"
        bare = m.rsplit("/", 1)[-1]
        prov = provider_guess(m) or (m.split("/", 1)[0] if "/" in m else None)
        if prov and f"{prov}/{bare}" in self.or_models:
            return self.or_models[f"{prov}/{bare}"], "openrouter-guess"
        n = norm(bare)
        if n:
            best = None
            for i, r in self.or_models.items():
                if (prov and r.get("provider") != prov) or not prov:
                    continue
                ni = norm(i.split("/", 1)[1])
                if ni == n:
                    d = 0
                elif ni.startswith(n) or n.startswith(ni):
                    d = abs(len(ni) - len(n)) + 1
                else:
                    continue
                if best is None or (d, len(i)) < best[0]:
                    best = ((d, len(i)), r)
            if best:
                return best[1], "openrouter-fuzzy"
        return None, "none"

    def resolve(self, model):
        """-> (row or None, price_source): yaml | openrouter-exact | openrouter-guess | openrouter-fuzzy | none"""
        m = (model or "").lower()
        if m not in self._src:
            r = self.rates(m)
            if r and r.get("input") is None and r.get("output") is None:
                r = None  # row exists but carries no rates (page unreadable): fall through to OpenRouter
            self._src[m] = (r, "yaml") if r else (self._openrouter(m) if m else (None, "none"))
        return self._src[m]

    def rates(self, model):
        """Exact id (case-insensitive), else the longest table id that model starts with (dated variants)."""
        m = (model or "").lower()
        if m not in self._cache:
            r = self.models.get(m)
            if r is None:
                ids = [i for i in self.models if m.startswith(i + "-") or m.endswith("/" + i)]
                r = self.models[max(ids, key=len)] if ids else None
            self._cache[m] = r
        return self._cache[m]

    def cost(self, model, input_tokens=0, cache_read=0, cache_write=0, output=0):
        r = self.resolve(model)[0]
        if not r:
            return None
        total = 0.0
        wr = r.get("cache_write_input")
        for n, rate in ((int(input_tokens or 0), r.get("input")),
                        (int(cache_write or 0), r.get("input") if wr is None else wr),
                        (int(cache_read or 0), r.get("cached_input")), (int(output or 0), r.get("output"))):
            if n:
                if rate is None:
                    return None
                total += n * float(rate)
        return round(total / 1e6, 6)


_P = []


def prices():
    if not _P:
        _P.append(Prices())
    return _P[0]
